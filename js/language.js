// Global translation app logic
const LanguageEngine = {
    currentLang: 'en',
    
    init: function() {
        // Read saved lang or default to browser setting (fallback to 'en')
        const savedLang = localStorage.getItem('dream_travel_lang');
        if (savedLang === 'vi' || savedLang === 'en') {
            this.currentLang = savedLang;
        } else {
            const browserLang = navigator.language || navigator.userLanguage;
            this.currentLang = browserLang.startsWith('vi') ? 'vi' : 'en';
        }
        
        this.applyLanguage(this.currentLang);
        
        // Setup triggers
        document.addEventListener('DOMContentLoaded', () => {
            this.syncSelectors();
            this.translatePage();
        });
    },
    
    setLanguage: function(lang) {
        if (lang !== 'en' && lang !== 'vi') return;
        this.currentLang = lang;
        localStorage.setItem('dream_travel_lang', lang);
        this.applyLanguage(lang);
        this.syncSelectors();
        this.translatePage();
        
        // Dispatch language change event for other custom rendering scripts (e.g. destinations grid, planners)
        const event = new CustomEvent('languageChanged', { detail: { language: lang } });
        document.dispatchEvent(event);
    },
    
    applyLanguage: function(lang) {
        document.documentElement.lang = lang;
    },
    
    syncSelectors: function() {
        const flagText = document.getElementById('selected-lang-text');
        const flagImg = document.getElementById('selected-lang-flag');
        
        if (flagText && flagImg) {
            if (this.currentLang === 'vi') {
                flagText.innerText = "Tiếng Việt";
                flagImg.src = "https://flagcdn.com/16x12/vn.png";
            } else {
                flagText.innerText = "English";
                flagImg.src = "https://flagcdn.com/16x12/us.png";
            }
        }
    },
    
    translatePage: function() {
        const dict = TRANSLATIONS[this.currentLang];
        if (!dict) return;
        
        // Translate text elements
        const elements = document.querySelectorAll('[data-i18n]');
        elements.forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (dict[key]) {
                el.innerText = dict[key];
            }
        });
        
        // Translate placeholder elements
        const inputs = document.querySelectorAll('[data-i18n-placeholder]');
        inputs.forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            if (dict[key]) {
                el.setAttribute('placeholder', dict[key]);
            }
        });
    },

    getText: function(key) {
        return TRANSLATIONS[this.currentLang][key] || key;
    }
};

// Start the engine
LanguageEngine.init();
